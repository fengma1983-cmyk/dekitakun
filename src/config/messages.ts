export function getReturnMessage(): string {
  return RETURN_MESSAGES[Math.floor(Math.random() * RETURN_MESSAGES.length)];
}

// =====================================================================
// 3. INVITATION_MESSAGES — 誘いカード本体 (v1.1 新設 / PRD 3.6)
// =====================================================================
// なぜ命令形を使わないか (PRD 3.6.1):
//   「始めなさい」は管理者の声。v1.1 は同行者になる。
//   「始めてみる？」は、選択権が本人にあることを言葉で表す。
//
// なぜ onTimeLate を別文にするか:
//   開始時刻を過ぎていても「過ぎている」ことを指摘しない (禁止ワード)。
//   ただ「始めてみる？」と、過去ではなく今を起点に声をかける。
// =====================================================================

export const INVITATION_MESSAGES = {
  // 開始 5 分前の軟提醒。画面下部に静かに出す (覆わない)。
  prePrompt: (task: Task) =>
    `あと 5 分で ${task.icon ?? ""} ${task.title} の時間だよ`,

  // 時刻到達時 (定時)
  onTime: (task: Task) => ({
    title: `${task.icon ?? ""} ${task.title} の時間だよ`,
    moodLabel: "今の気分は？",
    moods: ["😊", "😐", "😅"],
    options: {
      start:  "始めてみる",
      snooze: "あと 5 分",
      later:  "後にする",
    },
  }),

  // 時刻から数分経過した場合。口調は onTime より更に柔らかく、
  // 過去を参照しない (「始めてみる？」と今を起点に)。
  onTimeLate: (task: Task) => ({
    title: `${task.icon ?? ""} ${task.title}、始めてみる？`,
    moodLabel: "今の気分は？",
    moods: ["😊", "😐", "😅"],
    options: {
      start:  "始めてみる",
      snooze: "あと 5 分",
      later:  "後にする",
    },
  }),

  // 「あと 5 分」選択後の再提示。当日このタスクへの最後の声かけ。
  onTimeRetry: (task: Task) => ({
    title: `${task.icon ?? ""} ${task.title}、どう？`,
    options: {
      start: "始めてみる",
      later: "やっぱり 後にする",
    },
  }),

  // 応答後の短いフィードバック。責めない。
  ackStart:  "いいね、いってらっしゃい",
  ackSnooze: "わかった、また 5 分後に",
  ackLater:  "わかった、またね",
} as const;

// =====================================================================
// 4. MIN_START_MESSAGES — 最小起動機制 (v1.1 新設 / PRD 3.6.4)
// =====================================================================
// なぜカテゴリで分岐するか:
//   「全部やる」ではなく「1 問だけ」という極小ハードルで入口を作る。
//   ただし「遊び」「食事」「入浴」に最小起動を出すのは不自然なので、
//   getMinStartMessage は null を返して提示自体をスキップする。
//
// なぜ onStart / onContinue を分けるか:
//   「1 問だけ」で入った後、自然に次の 1 問を誘う流れを文案で作る。
//   これは強制ではなく、本人の力を信じる装置 (PRD 3.6.4)。
// =====================================================================

export const MIN_START_MESSAGES = {
  homework: {
    offer:       "最初の 1 問だけ、やってみる？",
    buttonLabel: "1 問だけ",
    onStart:     "いいね、1 問だけ やってみよう",
    onContinue:  "もう 1 問 いけそう？",
  },
  study: {
    offer:       "5 分だけタイマー、回してみる？",
    buttonLabel: "5 分だけ",
    onStart:     "5 分だけ、やってみよう",
    onContinue:  "もう 5 分 いけそう？",
  },
} as const;

// タスクの categoryId から最小起動メッセージを取得。
// 最小起動対象外 (遊び・食事・入浴等) では null を返す。
export function getMinStartMessage(
  categoryId: string
):
  | typeof MIN_START_MESSAGES.homework
  | typeof MIN_START_MESSAGES.study
  | null {
  if (categoryId === "homework") return MIN_START_MESSAGES.homework;
  if (categoryId === "study")    return MIN_START_MESSAGES.study;
  return null;
}

