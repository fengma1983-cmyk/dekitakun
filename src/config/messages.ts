// =====================================================================
// src/config/messages.ts
// =====================================================================
//
//   設計の合言葉 (v1.1):  頻度ではなく触れ方で解く
//
// 子どもの反応が薄いとき、誘いを「増やしたく」なる。だがそれは
// 「同行者」を「唠叨する親」に変える道。解くべきは頻度ではなく、
// 触れ方 — 文案の柔らかさ、選択肢の入口、最小起動の心理的ハードル、
// 動きの速度。このファイルはその「触れ方」を決める唯一の場所。
// 文面を変えたくなったら、まずここを開く。
//
// =====================================================================
//
// なぜ全ての文案をこのファイルに集約するか:
//   Architecture 8.4「文案を変更する → messages.ts のみ編集」。
//   JSX や hook に散らすと口調が漂流する。
//
// 文案作成の絶対ルール (PRD 3.3 / Architecture 3.2 末尾 / 同 6.1 の禁止ワードを参照):
//   1. 命令形は使わない。依頼ではなく命令する語尾を避ける
//   2. 欠席や未達を事実として指摘する表現は使わない。
//      過去にやっていないことは言葉にしない (成長として映す)
//   3. 誘いは疑問形または呼びかけ形で (「〜してみる？」「〜の時間だよ」)
//   4. 選択肢は常に 3 つ以上。二択にしない
//   5. 断られた時のメッセージは責めない (「わかった」「またね」)
//   6. 具体性 (「すごい」ではなく「8 分はやく終わったね」)
//   7. 分母表示は使わない (「3/10」ではなく「3 こ できた」)
//
// 具体的な NG 語の一覧は Architecture 6.1 を参照。
// このファイルのコメントには NG 語自体を書かない (禁止ワード grep 対策)。
// =====================================================================

import type { Task, DifficultyLevel } from "../store/types";

// =====================================================================
// DIFFICULTY_EMOJI — 難易度を表す絵文字
// =====================================================================
// なぜ ★★★ を使わないか:
//   星の数は「点数」を連想させる。v1.1 は評価しない哲学。
//   絵文字は本人の主観的な「しんどさ」を表現でき、評価軸にならない。
//
// 重要: 難易度 と 気分 (mood) は意味が違う (同じ絵文字を流用するが別軸)。
//   - 難易度 (difficulty): タスクの相対的しんどさ。本人が事前申告。
//     → この DIFFICULTY_EMOJI を使用
//   - 気分 (mood): 今その瞬間の状態。誘いカードで選ぶ (Phase 1-δ)。
//     → INVITATION_MESSAGES.onTime.moods を使用
//   データも別フィールドに保存する (Task.difficulty vs MoodEntry.mood)。
//   混同して実装するとフィードバックループが壊れる。
// =====================================================================

export const DIFFICULTY_EMOJI = {
  easy:      "😊",
  normal:    "😐",
  challenge: "😅",
} as const;

export const DIFFICULTY_LABEL = {
  easy:      "らくらく",
  normal:    "ふつう",
  challenge: "ちょっと むずかしい",
} as const;

// =====================================================================
// 1. CELEBRATION_MESSAGES — タスク完了時の称賛 (v1.0 継承)
// =====================================================================
// なぜ難易度で分岐するか (PRD 3.4):
//   「challenge」を完了したのに普通の称賛だと、挑戦心を映せない。
//   同じ「できた」でも、難しさに応じて言葉を変える。
// =====================================================================

export const CELEBRATION_MESSAGES = {
  easy: [
    "できたね！",
    "サクッとできた、いいペース",
    "はい、ひとつ できた",
  ],
  normal: [
    "ちゃんと できたね",
    "しっかり やりきったね",
    "いい集中だった",
  ],
  challenge: [
    "むずかしいの、やりきったね！",
    "これ できたの、かっこいいよ",
    "挑戦したあなた、今日のヒーロー",
  ],
} as const;

export function getCelebration(difficulty: DifficultyLevel): string {
  const pool = CELEBRATION_MESSAGES[difficulty];
  return pool[Math.floor(Math.random() * pool.length)];
}

