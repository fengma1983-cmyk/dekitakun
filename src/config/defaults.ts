// =====================================================================
// 一日の4帯 (Day Bands) — Ribbon レイアウトの背景色分け
// =====================================================================
// なぜ 4 帯に区切るか:
//   11 歳の時間感覚は「朝・学校・放課後・夜」で直感的に把握される。
//   連続する 15 分スロットのストリップよりも、帯で大まかに
//   「今どこにいる」を示す方が身体感覚に合う (Claude Design B variant)。
// なぜ「よる」だけ dark:true か:
//   一日のクロージング感を色で表す。ribbon 末尾に深い色が来ることで
//   「もう終わりに近い」が言葉なしで伝わる (指摘の言葉を使わずに
//   時間経過を視覚で感じてもらうメタファー)。
// startSlot/endSlot は 15 分単位で、0 = 06:00 から始まる (TIME_CONFIG 参照)。
// =====================================================================

export interface DayBand {
  id: "morning" | "school" | "after" | "night";
  label: string;
  startSlot: number;
  endSlot: number;
  color: string;
  dark?: boolean;   // true なら帯の中のテキストは白
}

